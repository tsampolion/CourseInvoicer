package gr.edusuite.invoicer.ui.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/** EduSuite spacing on a 4dp grid (guide §4). */
object Space {
    /** Icon-to-text gaps, between stacked text lines. */
    val xs: Dp = 4.dp

    /** Between tiles in a grid, between chips. */
    val s: Dp = 8.dp

    /** Inside chips and rows, between list items. */
    val m: Dp = 12.dp

    /** Screen edges, tile padding. */
    val l: Dp = 16.dp

    /** Between sections. */
    val xl: Dp = 24.dp

    /** Above the home header, empty-state padding. */
    val xxl: Dp = 32.dp
}
